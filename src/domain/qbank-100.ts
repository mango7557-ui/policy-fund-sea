/**
 * 사용자의 자연어 질문을 질문은행 100선(20대 중분류)과 매칭하여 최적의 의도·NBQ·표준가이드를 반환
 */
export function matchQuestionBankIntent(userQuery: string): CoreQuestionSpec | null {
  const normalized = userQuery.trim();
  if (!normalized) return null;

  let bestMatch: CoreQuestionSpec | null = null;
  let bestScore = 0;

  for (const spec of POLICY_QBANK_CATEGORIES_20) {
    let score = 0;
    for (const kw of spec.keywords) {
      if (normalized.includes(kw)) {
        score += 2;
      }
    }
    if (score > bestScore) {
      bestScore = score;
      bestMatch = spec;
    }
  }

  return bestScore > 0 ? bestMatch : null;
}
